package com.orchestra.subscriptions.access;

/**
 * Отвечает на единственный вопрос: числится ли имя аккаунта за какой-то подпиской в НАШЕЙ базе.
 *
 * <p>Нужен провайдеру доступа, когда {@code createUser} натыкается на уже существующее имя.
 * Снаружи два случая выглядят одинаково, а поступать с ними надо противоположно:
 * <ul>
 *   <li><b>наш недоделанный аккаунт</b> — прошлый {@code createUser} прошёл, а транзакция базы
 *       откатилась. За именем никто не числится, аккаунт надо подобрать и доиспользовать,
 *       иначе повторная попытка будет вечно натыкаться на конфликт и оплата не активируется;</li>
 *   <li><b>чужой рабочий аккаунт</b> — имя уже принадлежит другой подписке. Подобрать его
 *       значило бы слить две подписки в одну: общий срок, общий лимит устройств, общая
 *       ссылка — то есть человек платит дважды, а получает одно.</li>
 * </ul>
 *
 * <p>Интерфейс объявлен здесь, а реализация живёт в сервисном слое: слой выдачи доступа
 * описывает, что ему нужно, и не знает ни про JPA, ни про таблицу подписок.
 */
public interface AccountOwnership {

    /** {@code true} — имя уже закреплено за существующей подпиской. */
    boolean ownedBySubscription(String providerUsername);
}
